export function nameFor(value, language) {
  if (!value || language === 'ja') return value;
  const remainder = value.normalize('NFKC').replace(/^\d+号線/, '').replace(/^\((.+)\)$/, '$1');
  if (language === 'en') return namesEn[value] || namesEn[remainder] || value;
  return namesZh[value] || namesZh[remainder] || Array.from(remainder, char => kanji.get(char) || char).join('');
}

export function searchKey(text) {
  return text.toLowerCase().normalize('NFKD').replace(/\p{Mark}|[\s'’・-]/gu, '');
}

const localeTags = { zh: 'zh-CN', ja: 'ja-JP', en: 'en-US' };
export const languageStorageKey = 'japan-rail-atlas-language';
export const themeStorageKey = 'japan-rail-atlas-theme';

export function storedLanguage() {
  try {
    const language = localStorage.getItem(languageStorageKey);
    if (Object.hasOwn(locales, language)) return language;
  } catch {
    // Storage unavailable
  }
  return 'zh';
}

export function storedTheme() {
  try {
    const theme = localStorage.getItem(themeStorageKey);
    if (theme === 'light' || theme === 'dark') return theme;
  } catch {
    // Storage unavailable
  }
  return 'light';
}

export function labelsFor(language) {
  const tag = localeTags[language];
  const copy = locales[language];
  const formatter = new Intl.NumberFormat(tag);
  const signedPercent = new Intl.NumberFormat(tag, { maximumFractionDigits: 1, minimumFractionDigits: 0, signDisplay: 'exceptZero' });
  const plainPercent = new Intl.NumberFormat(tag, { maximumFractionDigits: 1, minimumFractionDigits: 0 });
  return {
    tag,
    language,
    copy,
    t: (key, values = {}) => (copy[key] || key).replace(/\{(\w+)\}/g, (marker, name) => values[name] ?? marker),
    name: name => nameFor(name, language),
    number: number => formatter.format(number),
    signedPct: value => signedPercent.format(value) + '%',
    pct: value => plainPercent.format(value) + '%',
  };
}
